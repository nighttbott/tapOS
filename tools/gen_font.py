#!/usr/bin/env python3
"""Regenerates src/text/font8x16.h from a PSF1 console font (256 glyphs, 8x16).
Usage: tools/gen_font.py [/usr/share/consolefonts/Lat15-VGA16.psf.gz] > src/text/font8x16.h"""
import gzip
import sys

path = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/consolefonts/Lat15-VGA16.psf.gz"
data = gzip.open(path).read() if path.endswith(".gz") else open(path, "rb").read()
if data[:2] != b"\x36\x04" or data[3] != 16:
    sys.exit("expected a PSF1 font with 16 rows per glyph")
glyphs = data[4:4 + 256 * 16]

print("#ifndef _FONT8X16_H")
print("#define _FONT8X16_H")
print("")
print("#include <stdint.h>")
print("")
print("/* 8x16 bitmap font, 256 glyphs of 16 rows; the most significant bit is the leftmost pixel.")
print(" * Generated by tools/gen_font.py from the console-setup VGA font. */")
print("static const uint8_t font8x16[256][16] = {")
for code in range(256):
    row = ", ".join("0x%02X" % b for b in glyphs[code * 16:(code + 1) * 16])
    print("    {%s}," % row)
print("};")
print("")
print("#endif")
